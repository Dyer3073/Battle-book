export function signalFamilyName(key: SignalFamilyKey): string {
  return SIGNAL_FAMILIES.find((f) => f.key === key)?.name ?? key;
}

export function signalSearchText(e: SignalEntry): string {
  return [e.name, e.meaning, e.use ?? "", e.source, e.flag ?? "", e.service, signalFamilyName(e.family), e.steps.join(" "), e.diagram.note]
    .join(" ")
    .toLowerCase();
}
