// Uniforms — static reference data transcribed from the researched
// uniforms pack (~/workspace/military-app/uniforms/uniforms.md,
// researched November 2026). Every entry's name, occasion, component
// list (wear order), assembly notes, flags, and regulation citation
// come only from the pack, which drew only on each branch's uniform
// regulation and official uniform pages. Placement notes are SUMMARY
// level; where exact placement matters the entry routes to the
// regulation — no measurements are printed anywhere.
//
// Fidelity rules baked into this data (the pack's flags, preserved):
// - Transitional uniforms carry their official status and dates
//   (AGSU mandatory possession 1 Oct 2027, ASU optional dress after
//   30 Sep 2027; USSF service-dress rollout incl. PTG mandatory
//   1 Feb 2026; USMC Uniform Board 221 updates; AF PTU phased fielding).
// - The Coast Guard "SDB Alpha/Bravo" labels are NOT shipped — the
//   pack found them only in secondary sources; the verified manual
//   text prescribes the light blue shirt with SDB.
// - Space Force mess dress and the new USSF service dress carry the
//   pack's "guidance still publishing — re-verify" flags.
// - CG PTU carries its no-single-prescribed-table note.
// - The pack's deliberate exclusions (flight duty uniforms, Navy
//   coveralls/2POC, ceremonial/honor-guard/band uniforms, maternity
//   variants) are NOT entries — they appear in NOT_COVERED below.
// - Space Force sits under SPFI 36-2903 (+ SPFGM 2026-01), never
//   folded into the Air Force group.

export type UniformLink = { label: string; url: string };

export type HeadgearKind =
  | "cap" // service / combination / frame cap
  | "garrison" // garrison / flight cap
  | "patrol" // patrol cap
  | "cover8" // eight-point utility cover
  | "dixie" // Dixie cup
  | "ballcap"
  | "watchcap"
  | "none";

export type TopKind = "coat" | "choker" | "mess" | "shirt" | "camo" | "jumper" | "pt";
export type BottomKind = "trousers" | "shorts" | "skirt";

export type DiagramLabel = {
  text: string;
  side: "left" | "right";
  /** Vertical anchor, 0 (top) – 1 (bottom) of the figure area. */
  y: number;
};

/** Stylized front-view figure spec — drawn by UniformDiagram.tsx. */
export type FigureSpec = {
  headgear: HeadgearKind;
  headgearColor: string;
  top: TopKind;
  topColor: string;
  /** Camo blob tones (top = "camo" only). */
  camoTones?: [string, string];
  bottom: BottomKind;
  bottomColor: string;
  stripeColor?: string;
  bloused?: boolean;
  beltColor?: string;
  cummerbundColor?: string;
  tieColor?: string;
  bowTie?: boolean;
  neckerchief?: boolean;
  ribbons?: boolean;
  medals?: "full" | "mini";
  nameTag?: boolean;
  /** Hexagonal name tag (Space Force pattern). */
  hexNameTag?: boolean;
  tapes?: boolean;
  tapeColor?: string;
  chestRank?: boolean;
  collarDevices?: boolean;
  shoulderBoards?: boolean;
  sleevePatches?: boolean;
  /** Gold shield device on the wearer's right sleeve (CG coat). */
  sleeveDevice?: boolean;
  /** Officer sleeve lace at the cuffs. */
  cuffLace?: boolean;
  diagonalButtons?: boolean;
  shirtText?: string;
  sword?: boolean;
  gloves?: boolean;
  footwear: "shoes" | "boots" | "runners";
  footwearColor: string;
  /** Cold-weather callout strip labels (PT uniforms), drawn under the figure. */
  callout?: string[];
  labels: DiagramLabel[];
};

export type UniformEntry = {
  id: string;
  name: string;
  /** Occasion class as the regulation frames it. */
  worn: string;
  variants?: string;
  /** Component list in wear order: headgear first, outerwear/optional last. */
  components: string[];
  /** Summary-level placement notes, only where the pack includes them. */
  assemblyNotes?: string;
  /** The pack's flags, rendered as written (transitional dates, re-verify). */
  flags?: string[];
  /** Governing regulation citation for this uniform. */
  regulation: string;
  /** Per-uniform official links, only where the pack provides them. */
  sources: UniformLink[];
  /** Extra diagram context the pack's spec calls out (insets/callouts). */
  diagramNote?: string;
  figure: FigureSpec;
};

export type UniformBranchGroup = {
  branch: string;
  regulation: string;
  note?: string;
  /** Branch-level official links. */
  sources: UniformLink[];
  uniforms: UniformEntry[];
};

